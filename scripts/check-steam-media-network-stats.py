#!/usr/bin/env python3
"""Compare production frame statistics and ordinary/FEC RX with original client.

The fixture is generated by executing pinned official instructions. All float
triples compare by bits, including folds, empty Stop and unweighted averages.
Full original packet/collector/report state is checked alongside frame stats.
"""

import argparse
import gzip
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def run(command, actions):
    p = subprocess.run(
        command,
        input="\n".join(" ".join(map(str, a)) for a in actions) + "\n",
        text=True,
        capture_output=True,
        timeout=15,
    )
    assert p.returncode == 0, (
        command,
        p.returncode,
        p.stdout[-2000:],
        p.stderr[-2000:],
    )
    return [json.loads(line) for line in p.stdout.splitlines()]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--collector", type=Path, required=True)
    p.add_argument("--receiver", type=Path, required=True)
    a = p.parse_args()
    data = json.loads(
        gzip.decompress(
            (
                ROOT / "scripts/fixtures/steam-media-network-stats-reference.json.gz"
            ).read_bytes()
        )
    )
    states = 0
    for case in data["component_cases"]:
        i = case["input"]
        got = run([str(a.collector.resolve())], i["actions"])
        assert len(got) == len(case["observed"]), i["name"]
        for n, (actual, expected) in enumerate(zip(got, case["observed"])):
            assert actual == expected, (i["name"], n, actual, expected)
        states += len(got)
    for case in data["pipeline_cases"]:
        i = case["input"]
        full = str(int(i["full"])) if "full" in i else "-1"
        got = run(
            [str(a.receiver.resolve()), str(int(i["crc"])), "1", full, "34", "quality"],
            i["actions"],
        )
        assert len(got) == len(case["observed"]), i["name"]
        for n, (actual, expected) in enumerate(zip(got, case["observed"])):
            assert actual == expected, (i["name"], n, actual, expected)
        states += len(got)
    scores = data["score_cases"]
    got = run([str(a.collector.resolve())], [["T"] + x["input"] for x in scores])
    assert len(got) == len(scores)
    for actual, expected in zip(got, scores):
        assert actual == expected["observed"], (expected, actual)
    print(
        f"Media network stats: {len(data['component_cases'])} component cases, {len(data['pipeline_cases'])} packet pipelines, {states} states, {len(scores)} score inputs passed"
    )


if __name__ == "__main__":
    main()
