static void from_hex(const char *hex, void *output, size_t size) {
    assert(strlen(hex) == size * 2);
    auto *p = static_cast<unsigned char *>(output);
    for (size_t i = 0; i < size; ++i) {
        unsigned value;
        assert(sscanf(hex + i * 2, "%2x", &value) == 1);
        p[i] = static_cast<unsigned char>(value);
    }
}
static void equal_hex(const void *data, size_t size, const char *hex) {
    unsigned char expected[128];
    assert(size <= sizeof(expected));
    from_hex(hex, expected, size);
    assert(!memcmp(data, expected, size));
}
